export const GLYPH_W = 5;
export const GLYPH_H = 7;

export class Font {
  constructor() { this.cache = new Map(); }

  _glyphCanvas(ch, color, scale) {
    const key = `${ch}|${color}|${scale}`;
    let c = this.cache.get(key);
    if (c) return c;
    const rows = GLYPHS[ch] || GLYPHS['?'];
    c = document.createElement('canvas');
    c.width = GLYPH_W * scale;
    c.height = GLYPH_H * scale;
    const g = c.getContext('2d');
    g.fillStyle = color;
    for (let y = 0; y < GLYPH_H; y++) {
      for (let x = 0; x < GLYPH_W; x++) {
        if (rows[y][x] === '#') g.fillRect(x * scale, y * scale, scale, scale);
      }
    }
    this.cache.set(key, c);
    return c;
  }

  width(text, scale = 1, spacing = 1) {
    return text.length * (GLYPH_W + spacing) * scale - spacing * scale;
  }

  /** Draws text; align: 'left' | 'center' | 'right'. Optional shadow colour. */
  draw(ctx, text, x, y, { color = '#e8e2c8', scale = 1, align = 'left', shadow = null, spacing = 1 } = {}) {
    text = String(text).toUpperCase();
    const w = this.width(text, scale, spacing);
    let cx = align === 'center' ? x - Math.floor(w / 2) : align === 'right' ? x - w : x;
    cx = Math.round(cx);
    y = Math.round(y);
    const step = (GLYPH_W + spacing) * scale;
    if (shadow) {
      let sx = cx;
      for (const ch of text) { ctx.drawImage(this._glyphCanvas(ch, shadow, scale), sx + scale, y + scale); sx += step; }
    }
    for (const ch of text) { ctx.drawImage(this._glyphCanvas(ch, color, scale), cx, y); cx += step; }
    return w;
  }
}
